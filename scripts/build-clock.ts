/**
 * Bundles fake-timers for injection into extension service workers before extension code runs.
 * Playwright's clock controls pages but does not install fake timers in service workers.
 * @sinonjs/fake-timers ships CommonJS source rather than a standalone browser bundle,
 * so we bundle its dependencies into an IIFE that can run without Node's module loader.
 *
 * The generated TypeScript module exports the bundle as a string for the worker init script.
 * It is regenerated during prepare/build, ignored by Git, and included in the published package,
 * so consumers need neither a bundler nor runtime access to the fake-timers package.
 * Dependency license notices are preserved in the injected source.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { build } from 'esbuild';

await buildClock();

async function buildClock() {
  const licenses = await readLicenses();
  const result = await build({
    entryPoints: ['@sinonjs/fake-timers'],
    bundle: true,
    platform: 'browser',
    format: 'iife',
    globalName: '__sinonFakeTimers',
    // Sinon only requires util when a Node process global exists; workers never enter that branch.
    external: ['util'],
    write: false,
    banner: { js: licenses.join('\n') },
  });
  await mkdir('src/clock/generated', { recursive: true });
  await writeFile(
    'src/clock/generated/fake-timers.ts',
    `// Generated by scripts/build-clock.ts.\nconst source: string = ${JSON.stringify(result.outputFiles[0].text)};\nexport default source;\n`,
  );
}

async function readLicenses() {
  const require = createRequire(import.meta.url);
  return Promise.all(
    ['@sinonjs/fake-timers', '@sinonjs/commons', 'type-detect'].map(async (name) => {
      const license = await readFile(require.resolve(`${name}/LICENSE`), 'utf8');
      return `/*! ${name}\n${license}\n*/`;
    }),
  );
}
