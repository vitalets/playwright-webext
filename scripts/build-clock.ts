/**
 * Bundles the pinned Playwright clock for injection before extension worker code runs.
 * Consumers use the generated source string without runtime access to upstream internals.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { build } from 'esbuild';

await buildClock();

async function buildClock() {
  const upstream = await readFile('src/clock/worker-clock/from-playwright/clock.ts', 'utf8');
  const license = upstream.slice(0, upstream.indexOf('*/') + 2);
  const upstreamBundle = await build({
    entryPoints: ['src/clock/worker-clock/from-playwright/clock.ts'],
    bundle: true,
    platform: 'browser',
    format: 'iife',
    globalName: '__playwrightClock',
    write: false,
    banner: { js: license },
  });
  const result = await build({
    stdin: {
      contents:
        "export { installWorkerClock } from './src/clock/worker-clock/playwright-wrapper.ts';",
      resolveDir: process.cwd(),
      loader: 'ts',
    },
    // The Node-only script builder is omitted from the worker bundle.
    external: ['./generated/playwright-clock.js'],
    bundle: true,
    platform: 'browser',
    format: 'iife',
    globalName: '__webextClockInstaller',
    write: false,
    banner: { js: upstreamBundle.outputFiles[0].text },
  });
  await mkdir('src/clock/worker-clock/generated', { recursive: true });
  await writeFile(
    'src/clock/worker-clock/generated/playwright-clock.ts',
    `// Generated by scripts/build-clock.ts.\nconst source: string = ${JSON.stringify(result.outputFiles[0].text)};\nexport default source;\n`,
  );
}
